// The map figures' base bodies (docs/looks.md §3.1): 24x36, the soles on row 34, the head on rows 3-12. Drawn by
// hand over ComfyUI drafts in the example's palette (Cloud's face): the 3/4 view faces left (right is it mirrored),
// the front faces the viewer, the back turns away. Letters: K L outline; O H J F Q skin (light to dark, J the colour);
// M P the eyes (P the colour); N the eye's white; V W T X the plain grey underclothes.
//
// A facing's walk is four frames: passing, a step, passing, the other step (the body one lower on a step, the planted
// foot on the sole row, the other lifted); its idle frame is the standing pose, which may differ from passing (the
// woman stands with her weight on one leg but walks on both).

