export const ICON_KEYS = [...Object.keys(I), ...Object.keys(POTION_COLORS)]

export function iconSheet(sprite: string, opts: { material?: string; element?: string } = {}): Sheet {
  const key = (sprite || '').split(':').pop()!.toLowerCase()
  const def: IconDef = key.startsWith('potion') ? potion(key) : I[key] ?? I[ALIAS[key] ?? ''] ?? I.pouch
  const matBase = opts.material && /^#?[0-9a-f]{3,6}$/i.test(opts.material) ? (opts.material.startsWith('#') ? opts.material : '#' + opts.material) : (def.mat ?? '#9aa0aa')
  const el = opts.element && ELEMENT_COLORS[opts.element] ? ELEMENT_COLORS[opts.element] : undefined
  let matLight = shade(matBase, 0.38)
  if (el) matLight = mix(matLight, el.light, 0.3)
  const pal: Record<string, string> = {
    M: matBase,
    m: shade(matBase, -0.3),
    N: matLight,
    k: shade(matBase, -0.55),
    W: '#9a6a3a',
    w: '#6a4424',
    V: '#c08a50',
    G: '#e0b040',
    g: '#a87c20',
    Y: '#fbe27a',
    L: '#8a5a34',
    l: '#5e3a22',
    j: '#b07a48',
    X: '#ffffff',
    K: '#2a2230',
    ...(def.pal ?? {}),
  }
  const p = new Pix(16, 16)
  p.stamp(def.g, pal)
  def.post?.(p, pal)
  if (el) {
    const [gx, gy] = def.gem ?? [11, 11]
    if (gx >= 0) {
      p.set(gx, gy, el.base)
      p.set(gx + 1, gy, el.dark)
      p.set(gx, gy + 1, el.dark)
      p.set(gx + 1, gy + 1, el.base)
      p.set(gx, gy, el.light)
    } else {
      // the whole icon is a gem: recolour material pixels to the element
      p.map((c) => (c === pal.M ? el.base : c === pal.m ? el.dark : c === pal.N ? el.light : c === pal.k ? shade(el.dark, -0.3) : c))
    }
  }
  p.outline(OUTLINE, 0.82)
  if (el) {
    // soft elemental aura hugging the silhouette, plus one twinkle
    const src = p.clone()
    for (let y = 0; y < 16; y++)
      for (let x = 0; x < 16; x++) {
        if (src.alpha(x, y)) continue
        let n = 0
        for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (src.alpha(x + dx, y + dy) > 100) n++
        if (n) p.set(x, y, el.glow, Math.min(0.55, 0.22 + n * 0.08))
      }
    const tw: [number, number][] = [
      [13, 2],
      [2, 3],
      [13, 12],
    ]
    const spot = tw.find(([x, y]) => !src.alpha(x, y) && !src.alpha(x - 1, y) && !src.alpha(x + 1, y) && !src.alpha(x, y - 1) && !src.alpha(x, y + 1))
    if (spot) {
      const [x, y] = spot
      p.set(x, y, '#ffffff')
      for (const [dx, dy] of [
        [1, 0],
        [-1, 0],
        [0, 1],
        [0, -1],
      ])
        p.set(x + dx, y + dy, el.light, 0.85)
    }
  }
  return pack([{ name: 'icon', pix: p }], 1)
}
