/** A slot's shape when its piece names none, by its form. */
const DEFAULT: Record<string, string> = {
  'item/armor/helmet': 'helm',
  'item/clothing/hood': 'hood',
  'item/clothing/hat': 'cap',
  'item/valuable/crown': 'circlet',
  'item/armor/pauldrons': 'pauldron',
  'item/clothing/cloak': 'cloak',
  'item/armor/breastplate': 'plate',
  'item/armor/jerkin': 'jerkin',
  'item/clothing/robe': 'robe',
  'item/clothing/gloves': 'glove',
  'item/clothing/belt': 'belt',
  'item/clothing/boots': 'boot',
  'item/valuable/amulet': 'amulet',
  'item/valuable/earring': 'earring',
  'item/valuable/ring': 'ring',
}

const hex = (c: string) => [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16)]
const toHex = (rgb: number[]) => `#${rgb.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')}`
/** The outline: the shade, darkened toward a warm black. */
const outlineOf = (dark: string) => toHex(hex(dark).map((v, i) => v * 0.35 + [30, 18, 14][i] * 0.65))

export function shapeOf(p: PieceDef): string {
  const name = p.shape && SHAPES[p.shape] ? p.shape : DEFAULT[p.form]
  if (!name || !SHAPES[name]) throw new Error(`sets: no shape for ${p.form} (${p.shape ?? 'default'})`)
  return name
}

for (const [name, grid] of Object.entries(SHAPES)) {
  if (grid.length !== 16 || grid.some((r) => r.length !== 16)) throw new Error(`sets: shape ${name} is not 16x16 (${grid.map((r) => r.length).join(',')})`)
}

function draw(s: SetDef, p: PieceDef): void {
  const [m, d, a, l] = s.palette
  writeIcon(`Items/Sets/${s.id}/${p.slot}.png`, SHAPES[shapeOf(p)], { m, d, a, l, o: outlineOf(d) })
}

let n = 0
for (const s of MAIN_SETS) for (const p of s.pieces) draw(s, p), n++
console.log(`sets: ${n} icons for ${MAIN_SETS.length} sets → public/assets/lsw/Items/Sets/`)
